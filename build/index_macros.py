"""The closed macro set of the Index sources, and the renderer for entry text.

Every macro occurring in ``tex/idx-*.tex`` and ``tex/app-*.tex`` is listed here.
There are 24, and the set really is closed -- ``emit_tex.py`` generates these
files from a reconciled extraction, so an unknown control sequence means either
that generator changed or somebody hand-edited something new in.  Either way the
build must stop rather than guess.

The rendering table is an ordered list, and the order is load-bearing:
``\\seealso`` must be tried before ``\\see``, and ``\\cf\\ `` (a control space)
before ``\\cf`` word-boundary, or the shorter rule eats the longer one's prefix
and leaves a stray backslash in the text.
"""

from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent
                       / "vendor" / "index"))
import cite  # noqa: E402

# --- structure -------------------------------------------------------------
LEVEL_OF = {"iA": 1, "iB": 2, "iC": 3, "iD": 4, "iE": 5, "iapp": 1}

# Entry macros: name -> number of brace arguments.  \iA is the only two-arg one.
ENTRY_MACROS = {"iA": 2, "iB": 1, "iC": 1, "iD": 1, "iE": 1, "iapp": 1}

# Appendix A chronology.  The MACRO is the parentage signal, not document order:
# a \chrontext hangs off the year even when it follows a \chronmonth.
CHRON_MACROS = {"chronyear": 0, "chronmonth": 0, "chrontext": 1, "chronsubtext": 2}

# Structural, not entries.
OTHER_MACROS = {"idivider", "iapptitle", "iappendixname", "begin", "end", "def"}

# Tool-owned files, regenerated by paginate.py on every `make pdf'.  They hold
# pagination decisions derived FROM the content and no content of their own.
IGNORE_FILES = {"app-pins.tex", "breaks.tex", "note.tex"}

KNOWN_ENVIRONMENTS = {"indexbody"}

# --- rendering -------------------------------------------------------------
RENDER = [
    (re.compile(r"\\cit\{([^}]*)\}"), r"(\1)"),
    (re.compile(r"\\seealso\{"), "See also "),
    (re.compile(r"\\see\{"), "See "),
    (re.compile(r"\\ab\{"), ""),
    (re.compile(r"\\ilost\{"), "["),
    (re.compile(r"\\qv\b"), "q.v."),
    (re.compile(r"\\cf\\ "), "cf: "),
    (re.compile(r"\\versus\\ "), "vs. "),
    (re.compile(r"\\versus\b"), "vs."),
    (re.compile(r"\\cf\b"), "cf:"),
]
RE_LEFTOVER = re.compile(r"\\[a-zA-Z@]+")
RE_ESCAPE = re.compile(r"\\([#$%&_^~{}])")
RE_CIT = re.compile(r"\\cit\{([^}]*)\}")
RE_XREF = re.compile(r"\\(see|seealso)\{([^}]*)\}")
RE_AB = re.compile(r"\\ab\{([^}]*)\}")
# A See clause, with the period that introduces it: "death. See also atonement".
RE_XREF_CLAUSE = re.compile(r"\.?\s*\\(?:see|seealso)\{[^}]*\}")
RE_QV = re.compile(r"\\qv\b")


def unescape(s: str) -> str:
    return RE_ESCAPE.sub(r"\1", s)


def render(s: str, where: str = "", report=None) -> str:
    """Entry source -> printed text.  Raises on anything outside the closed set."""
    for pat, rep in RENDER:
        s = pat.sub(rep, s)
    # Check for survivors BEFORE braces are stripped, so the message names the
    # macro as it was written rather than a run-together of macro and argument.
    leftover = RE_LEFTOVER.search(s)
    if leftover is None:
        s = s.replace("{", "").replace("}", "")
        s = unescape(s)
    if leftover:
        msg = f"unrendered macro {leftover.group(0)!r} survived render()"
        if report is not None:
            report.hard("index-unknown-macro", where, msg)
        else:
            raise ValueError(f"{where}: {msg}")
    return re.sub(r"\s+", " ", s).strip()


def label(s: str, where: str = "", report=None) -> str:
    r"""What an entry names, without what it points at: the margin chip.

    Exactly \cit{}, \see{}, \seealso{} and \qv come out, with the period
    that introduces a See clause.  Every other parenthesis is the editor's own
    words and stays -- "Adam (village)" and "Adam (original of Satania)" are two
    different people, and a chip that calls them both "Adam" has lost that.
    Stripping every parenthesis from the rendered text, as the chips used to,
    also took "(first)" off Isaiah and "(temporary members)" off Technical
    Advisers.
    """
    return render(RE_QV.sub("", RE_XREF_CLAUSE.sub("", RE_CIT.sub("", s))),
                  where, report)


# The HTML rendering.  Same closed set, same order, but it keeps what the plain
# form throws away: uindex.sty sets \ab, \see, \seealso, \qv, \cf, \versus and
# \ilost in italic, and a citation is a place in the book rather than a string.
def _cit_href(raw: str) -> str | None:
    r"""Where a \cit{} points.

    Uses the printed form directly when it is already a valid URL reference, so
    `48:6.2-4` links to the whole range and the reader arrives with all three
    paragraphs marked.  Otherwise the first expanded target: a comma list goes
    to its first paragraph, `76:2sec` to the section, `Paper 61` to the paper.
    """
    if RE_URLREF.match(raw):
        return "/" + raw
    c = cite.parse(raw)
    if c is None:
        return None
    for paper, sec, n in c.expand():
        if n is not None:
            return f"/{paper}:{sec}.{n}"
        if sec is not None:
            return f"/{paper}:{sec}"
        return f"/{paper}"
    return None


RE_URLREF = re.compile(r"^\d+:\d+(?:\.\d+(?:-\d+)?)?$")
_HTML = [
    (re.compile(r"\\seealso\{"), "<i>See also</i> "),
    (re.compile(r"\\see\{"), "<i>See</i> "),
    (re.compile(r"\\ab\{([^}]*)\}"), r"<i>\1</i>"),
    (re.compile(r"\\ilost\{([^}]*)\}"), r"<i>[\1]</i>"),
    (re.compile(r"\\qv\b"), "<i>q.v.</i>"),
    (re.compile(r"\\cf\\ "), "<i>cf:</i> "),
    (re.compile(r"\\versus\\ "), "<i>vs.</i> "),
    (re.compile(r"\\versus\b"), "<i>vs.</i>"),
    (re.compile(r"\\cf\b"), "<i>cf:</i>"),
]


def render_html(src: str, where: str = "", report=None) -> str:
    def cit(m):
        raw = m.group(1)
        href = _cit_href(raw)
        return (f'<a class="cit" href="{href}">({raw})</a>' if href
                else f"({raw})")
    s = RE_CIT.sub(cit, src)
    for pat, rep in _HTML:
        s = pat.sub(rep, s)
    leftover = RE_LEFTOVER.search(s)
    if leftover:
        msg = f"unrendered macro {leftover.group(0)!r} survived render_html()"
        if report is not None:
            report.hard("index-unknown-macro", where, msg)
        else:
            raise ValueError(f"{where}: {msg}")
    s = s.replace("{", "").replace("}", "")
    s = unescape(s)
    return re.sub(r"\s+", " ", s).strip()


def balanced(s: str, i: int) -> tuple[str, int]:
    """Read the balanced group whose opening brace is at s[i].

    The backslash skip is what keeps \\# \\% \\$ \\& -- and a future \\{ or \\}
    -- from disturbing the depth count.
    """
    depth, start = 0, i
    while i < len(s):
        if s[i] == "\\":
            i += 2
            continue
        if s[i] == "{":
            depth += 1
        elif s[i] == "}":
            depth -= 1
            if depth == 0:
                return s[start + 1:i], i + 1
        i += 1
    raise ValueError("unbalanced braces")
